def _boundary_filter_snapshot(rules: str, bridge: str) -> int:
    """Check exact first INPUT reject, then the effective ordered FORWARD path."""
    expected = ("-A INPUT -s 10.200.0.0/24 -d 172.30.0.1/32 -i " + bridge
                + " -p tcp -m tcp --dport 8000 -j REJECT --reject-with tcp-reset")
    if (not rules.startswith("# Generated by iptables-save ")
            or rules.count("\n*filter\n") != 1 or rules.count("\nCOMMIT\n") != 1
            or not rules.split("\nCOMMIT\n", 1)[1].startswith("# Completed on ")):
        raise RuntimeError("Trusted boundary snapshot format unavailable")
    chains = {name: [] for name in ("FORWARD", "DOCKER-USER", "DOCKER-FORWARD",
                                   "DOCKER-CT", "DOCKER-INTERNAL")}
    input_rules = []
    for line in rules.splitlines():
        if line.startswith(":FORWARD "):
            if not line.startswith(":FORWARD DROP ["):
                raise RuntimeError("Worker forwarding policy changed")
            chains["FORWARD"].append("-P FORWARD DROP")
        if not line.startswith("["):
            continue
        match = re.fullmatch(r"\[(\d+):(\d+)\] (\-A [A-Z-]+ .+)", line)
        if match is None:
            raise RuntimeError("Trusted boundary rule counters unavailable")
        command = match.group(3)
        if command.startswith("-A INPUT "):
            input_rules.append((int(match.group(1)), command))
        for name in chains:
            if command.startswith("-A " + name + " "):
                chains[name].append(command)
                break
    if not input_rules or input_rules[0][1] != expected:
        raise RuntimeError("Exact first worker bridge reject rule changed")
    rendered = {name: "\n".join(lines) for name, lines in chains.items()}
    if not effective_forwarding_denial(rendered, bridge):
        raise RuntimeError("Worker bridge forwarding rules changed")
    return input_rules[0][0]


def _read_boundary_counter(bridge: str) -> int:
    """Ask the fixed root-owned read-only helper; the worker never sees it."""
    with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as client:
        client.settimeout(7)
        client.connect(_BOUNDARY_SOCKET)
        client.sendall(b'{"operation":"filter-rules"}\n')
        data = bytearray()
        while b"\n" not in data:
            part = client.recv(65536)
            if not part or len(data) + len(part) > 1200000:
                raise RuntimeError("Trusted boundary snapshot unavailable")
            data.extend(part)
    record = json.loads(bytes(data).split(b"\n", 1)[0])
    if not isinstance(record, dict):
        raise RuntimeError("Trusted boundary snapshot unavailable")
    checked_at = record.get("checkedAt")
    if (record.get("status") != "ok" or not isinstance(checked_at, (int, float))
            or not 0 <= time.time() - checked_at <= 10
            or not isinstance(record.get("rules"), str)):
        raise RuntimeError("Trusted boundary snapshot unavailable")
    return _boundary_filter_snapshot(record["rules"], bridge)


def _presenter_worker_event(event: dict) -> dict | None:
    # Worker stdout is untrusted. Full SDK bodies stay in the private artifact;
    # the presenter receives only canonical tool metadata or fixed error codes.
    kind = event.get("kind")
    payload = event.get("payload")
    if not isinstance(payload, dict):
        return None
    if kind == "worker.activity":
        labels = {"browser": "Browser action", "terminal": "Terminal action",
                  "file_editor": "File editor action"}
        tool, status = payload.get("tool"), payload.get("status")
        if tool not in labels or status not in ("started", "succeeded", "failed"):
            return None
        clean = {"tool": tool, "status": status, "label": labels[tool]}
        turn_id = payload.get("turnId")
        if turn_id is not None:
            try:
                if not isinstance(turn_id, str) or str(UUID(turn_id)) != turn_id:
                    return None
            except ValueError:
                return None
            clean["turnId"] = turn_id
            call_id = payload.get("toolCallId")
            if (not isinstance(call_id, str) or not 1 <= len(call_id) <= 128
                    or not call_id.isprintable()):
                return None
            clean["toolCallId"] = call_id
            clean["title"] = labels[tool]
            verb = {"started": "started", "succeeded": "completed",
                    "failed": "failed"}[status]
            clean["description"] = labels[tool].replace(" action", " tool call") + " " + verb
    elif kind == "worker.assistant":
        text, turn_id, sdk_id = payload.get("text"), payload.get("turnId"), payload.get("sdkEventId")
        if (not isinstance(text, str) or not text.strip() or len(text) > 8192 or
                not isinstance(turn_id, str) or not isinstance(sdk_id, str) or
                not 1 <= len(sdk_id) <= 128 or not sdk_id.isprintable()):
            return None
        try:
            if str(UUID(turn_id)) != turn_id:
                return None
        except ValueError:
            return None
        clean = {"text": text, "turnId": turn_id, "sdkEventId": sdk_id}
    elif kind in ("worker.step", "worker.delta"):
        turn_id = payload.get("turnId")
        try:
            if not isinstance(turn_id, str) or str(UUID(turn_id)) != turn_id:
                return None
        except ValueError:
            return None
        clean = {"turnId": turn_id}
        if kind == "worker.delta":
            channel, text = payload.get("channel"), payload.get("text")
            if channel not in ("text", "reasoning") or not isinstance(text, str) or not 1 <= len(text) <= 2000:
                return None
            clean.update(channel=channel, text=text)
        else:
            call_id, tool, status = payload.get("toolCallId"), payload.get("tool"), payload.get("status")
            if (tool not in ("browser", "terminal", "file_editor") or
                    status not in ("started", "succeeded", "failed") or
                    not isinstance(call_id, str) or not 1 <= len(call_id) <= 128 or
                    not call_id.isprintable()):
                return None
            clean.update(toolCallId=call_id, tool=tool, status=status)
            for key, limit in (("thought", 1200), ("detail", 300), ("result", 400)):
                value = payload.get(key)
                if isinstance(value, str) and value.strip():
                    clean[key] = value[:limit]
    elif kind == "worker.sdk_error":
        error_type = payload.get("errorType")
        if not isinstance(error_type, str) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{0,79}", error_type):
            return None
        clean = {"errorType": error_type}
        if "turnId" in payload:
            turn_id = payload["turnId"]
            try:
                if not isinstance(turn_id, str) or str(UUID(turn_id)) != turn_id:
                    return None
            except ValueError:
                return None
            clean["turnId"] = turn_id
    elif kind == "worker.configuration_error":
        if payload.get("error") not in ("mission_fields_missing", "invalid_reasoning_effort",
                                         "unknown_scenario"):
            return None
        clean = {"error": payload["error"]}
    else:
        return None
    return {"kind": kind, "source": "host_filtered_openhands", "at": time.time(),
            "payload": clean}


